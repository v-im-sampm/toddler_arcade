import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const project = path.resolve(here, '..');
const source = path.join(project, 'assets', 'generated');
const target = path.join(project, 'device', 'build');
const header = path.join(project, 'device', 'main', 'sprite_pack.hpp');
const manifest = JSON.parse(fs.readFileSync(path.join(source, 'manifest.json'), 'utf8'));
const animated = /^(fish_|visitor_|weed_|rays_|caustics_|surface_|button_)/;
const selected = manifest.sprites.filter(({ id }) =>
  !animated.test(id) || Number(id.slice(id.lastIndexOf('_') + 1)) % 2 === 0);
const chunks = [];
const lines = [];
const signatureBytes = 16;
let offset = signatureBytes;
for (const { id, bounds, bytes } of selected) {
  const data = fs.readFileSync(path.join(source, id + '.bgra'));
  if (data.length !== bytes) throw new Error(`Sprite length mismatch: ${id}`);
  lines.push(`  {"${id}", ${offset}u, ${bounds[2]}, ${bounds[3]}},`);
  chunks.push(data);
  offset += bytes;
}
const partitionBytes = 0x5F0000;
if (offset > partitionBytes) throw new Error(`Sprite pack ${offset} exceeds asset partition ${partitionBytes}`);
fs.mkdirSync(target, { recursive: true });
fs.mkdirSync(path.dirname(header), { recursive: true });
const digest = crypto.createHash('sha256');
for (const chunk of chunks) digest.update(chunk);
const signature = digest.digest().subarray(0, signatureBytes);
fs.writeFileSync(path.join(target, 'sprite_assets.bin'), Buffer.concat([signature, ...chunks]));
fs.writeFileSync(header, `// Generated by tools/pack_device_assets.mjs; do not edit.
#pragma once
#include <cstdint>
namespace aquarium::pack {
struct Entry { const char* name; uint32_t offset; uint16_t width, height; };
inline constexpr uint8_t signature[] = {${[...signature].map(n => `0x${n.toString(16).padStart(2, '0')}`).join(', ')}};
inline constexpr Entry entries[] = {
${lines.join('\n')}
};
inline constexpr uint32_t bytes = ${offset}u;
}
`);
console.log(`Device sprite pack: ${selected.length} frames, ${offset} bytes (${(offset / 1048576).toFixed(2)} MiB); partition ${partitionBytes} bytes`);
