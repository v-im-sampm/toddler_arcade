// Little Arcade launcher on the ESP32-S3: a two-tile menu (Color Pop, Bubble Aquarium) on the
// board components. Color Pop's sprite pack is memory-mapped from `cp_assets`; the Aquarium pack
// is read from `assets` into PSRAM by its own view. Touch goes through launcher::Arcade, which
// gives Home (top-left) in either game a way back to the menu.
