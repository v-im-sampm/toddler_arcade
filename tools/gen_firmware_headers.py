#!/usr/bin/env python3
"""Generate firmware C++ headers from config/*.json.

config/commands.json   -> firmware/components/core/include/little_arcade/intent.hpp
config/board_pins.json -> firmware/components/board/include/little_arcade/board_pins.hpp

Usage: gen_firmware_headers.py [--check]
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INTENT_OUT = ROOT / "firmware/components/core/include/little_arcade/intent.hpp"
PINS_OUT = ROOT / "firmware/components/board/include/little_arcade/board_pins.hpp"
HEADER = "// GENERATED by tools/gen_firmware_headers.py from {src}. Do not edit.\n"
IDENT = re.compile(r"^[A-Z][A-Z0-9_]*$")


def camel(name):
    return "".join(p.capitalize() for p in name.split("_"))


def gen_intents(cfg):
    intents = sorted(cfg["intents"], key=lambda i: i["id"])
    contexts = []
    for i in intents:
        if not IDENT.match(i["name"]):
            raise ValueError(f"bad intent name {i['name']!r}")
        if i["id"] <= 0 or i["id"] > 255:
            raise ValueError(f"intent id out of range: {i['id']}")
        for c in i["contexts"]:
            if c not in contexts:
                contexts.append(c)
    if len(contexts) > 32:
        raise ValueError("more than 32 contexts")

    out = [HEADER.format(src="config/commands.json"), "#pragma once\n",
           "#include <cstddef>\n#include <cstdint>\n\nnamespace little_arcade {\n",
           f"inline constexpr int kCommandsSchemaVersion = {int(cfg['version'])};\n",
           "enum class Intent : uint8_t {\n  UNKNOWN = 0,\n"]
    out += [f"  {i['name']} = {i['id']},\n" for i in intents]
    out.append("};\n\n")

    out.append("enum class Context : uint32_t {\n")
    out += [f"  {camel(c)} = 1u << {n},\n" for n, c in enumerate(contexts)]
    out.append("};\n\n")
    out.append("constexpr uint32_t operator|(Context a, Context b) {\n"
               "  return static_cast<uint32_t>(a) | static_cast<uint32_t>(b);\n}\n"
               "constexpr uint32_t operator|(uint32_t a, Context b) { return a | static_cast<uint32_t>(b); }\n\n")

    out.append("struct IntentInfo {\n  Intent intent;\n  const char* name;\n  uint32_t context_mask;\n};\n\n")
    out.append(f"inline constexpr std::size_t kIntentCount = {len(intents)};\n")
    out.append("inline constexpr IntentInfo kIntentTable[kIntentCount] = {\n")
    for i in intents:
        mask = " | ".join(f"static_cast<uint32_t>(Context::{camel(c)})" for c in i["contexts"])
        out.append(f"    {{Intent::{i['name']}, \"{i['name']}\", {mask}}},\n")
    out.append("};\n\n")
    out.append("constexpr const IntentInfo* intent_info(Intent intent) {\n"
               "  for (const auto& info : kIntentTable) {\n"
               "    if (info.intent == intent) return &info;\n  }\n  return nullptr;\n}\n\n"
               "constexpr const char* intent_name(Intent intent) {\n"
               "  const IntentInfo* info = intent_info(intent);\n"
               "  return info ? info->name : \"UNKNOWN\";\n}\n\n"
               "// True if `intent` is declared for any context set in `active_contexts`.\n"
               "constexpr bool intent_allowed(Intent intent, uint32_t active_contexts) {\n"
               "  const IntentInfo* info = intent_info(intent);\n"
               "  return info && (info->context_mask & active_contexts) != 0;\n}\n\n"
               "}  // namespace little_arcade\n")
    return "".join(out)


def gen_pins(cfg):
    out = [HEADER.format(src="config/board_pins.json"), "#pragma once\n",
           "#include <cstdint>\n\nnamespace little_arcade::board {\n",
           "// -1 means TBD: not established. Drivers must refuse to start on a -1 pin.\n",
           "inline constexpr int kPinTbd = -1;\n",
           f"inline constexpr bool kPinsVerified = {'true' if cfg['verified'] is True else 'false'};\n",
           f"inline constexpr const char* kVerificationLevel = \"{cfg.get('verification_level', 'none')}\";\n",
           f"inline constexpr const char* kSchematicRevision = \"{cfg.get('schematic_revision', 'TBD')}\";\n",
           f"inline constexpr const char* kPhysicalPcbRevision = \"{cfg.get('physical_pcb_revision', 'TBD')}\";\n\n"]
    for group, body in cfg.items():
        if not (isinstance(body, dict) and isinstance(body.get("pins"), dict)):
            continue
        out.append(f"namespace {group} {{\n")
        for name, pin in body["pins"].items():
            gpio = pin["gpio"]
            value = "kPinTbd" if gpio == "TBD" else str(int(gpio))
            out.append(f"inline constexpr int k{camel(name)} = {value};\n")
        if group == "touch" and str(body.get("i2c_address", "TBD")).startswith("0x"):
            out.append(f"inline constexpr uint8_t kI2cAddress = {body['i2c_address']};\n")
        if group == "audio":
            source = body.get("wiring_evidence", {}).get("source", "none")
            bench = bool(body.get("wiring_evidence", {}).get("bench_tests"))
            out.append("// Wiring provenance; bench-verified only once H03 bench tests are recorded.\n")
            out.append(f"inline constexpr const char* kWiringSource = \"{source}\";\n")
            out.append(f"inline constexpr bool kWiringBenchVerified = {'true' if bench else 'false'};\n")
        out.append(f"}}  // namespace {group}\n\n")
    out.append("}  // namespace little_arcade::board\n")
    return "".join(out)


def main(argv):
    check = "--check" in argv
    jobs = [
        (INTENT_OUT, gen_intents(json.loads((ROOT / "config/commands.json").read_text(encoding="utf-8")))),
        (PINS_OUT, gen_pins(json.loads((ROOT / "config/board_pins.json").read_text(encoding="utf-8")))),
    ]
    stale = []
    for path, text in jobs:
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            if check:
                stale.append(path.relative_to(ROOT).as_posix())
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
                print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("STALE generated headers (run tools/gen_firmware_headers.py): " + ", ".join(stale))
        return 1
    if check:
        print("PASS: generated firmware headers are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
